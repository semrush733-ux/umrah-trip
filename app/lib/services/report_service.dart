import 'dart:io';

import 'package:intl/intl.dart';
import 'package:path_provider/path_provider.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:share_plus/share_plus.dart';

import '../models/trip.dart';
import 'app_state.dart';

/// Generates branded PDF reports (expenses / travel memories) and opens the
/// system share sheet (WhatsApp, AirDrop, email, save to files…).
class ReportService {
  static const _emerald = PdfColor.fromInt(0xFF086B58);
  static const _gold = PdfColor.fromInt(0xFFC8A96B);
  static const _slate = PdfColor.fromInt(0xFF18242B);

  static pw.Widget _header(String title) => pw.Container(
        padding: const pw.EdgeInsets.all(16),
        decoration: pw.BoxDecoration(
          color: _emerald,
          borderRadius: pw.BorderRadius.circular(10),
        ),
        child: pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
          children: [
            pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Text('UMRAH TRIP',
                    style: pw.TextStyle(
                        color: PdfColors.white,
                        fontSize: 20,
                        fontWeight: pw.FontWeight.bold,
                        letterSpacing: 3)),
                pw.Text('Your Smart Umrah & Ziyarat Companion',
                    style: const pw.TextStyle(color: _gold, fontSize: 9)),
              ],
            ),
            pw.Text(title,
                style: pw.TextStyle(
                    color: PdfColors.white,
                    fontSize: 13,
                    fontWeight: pw.FontWeight.bold)),
          ],
        ),
      );

  static pw.Widget _footer() => pw.Padding(
        padding: const pw.EdgeInsets.only(top: 10),
        child: pw.Text(
            'Generated by Umrah Trip · Sponsored by Bin-Mukhtar Travels · by BWP Experts',
            style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey600)),
      );

  static Future<void> _share(pw.Document doc, String filename) async {
    final dir = await getTemporaryDirectory();
    final file = File('${dir.path}/$filename');
    await file.writeAsBytes(await doc.save());
    await Share.shareXFiles([XFile(file.path)],
        text: 'Umrah Trip — $filename');
  }

  /// Expense report: totals, per-category breakdown, full ledger.
  static Future<void> shareExpenseReport(AppState app) async {
    final doc = pw.Document();
    final byCat = <String, double>{};
    for (final e in app.expenses) {
      byCat[e.category] = (byCat[e.category] ?? 0) + e.amountSar;
    }
    final total = app.totalSpentSar;
    final rate = app.pkrPerSar;

    doc.addPage(pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      footer: (_) => _footer(),
      build: (_) => [
        _header('Expense Report'),
        pw.SizedBox(height: 16),
        pw.Row(children: [
          _stat('Total spent', '${total.toStringAsFixed(0)} SAR'),
          pw.SizedBox(width: 10),
          if (rate != null)
            _stat('In PKR (rate ${rate.toStringAsFixed(2)})',
                '${(total * rate).toStringAsFixed(0)} PKR'),
          pw.SizedBox(width: 10),
          if (app.budgetSar != null)
            _stat('Budget remaining',
                '${(app.budgetSar! - total).toStringAsFixed(0)} SAR'),
        ]),
        pw.SizedBox(height: 16),
        pw.Text('By category',
            style: pw.TextStyle(fontSize: 14, fontWeight: pw.FontWeight.bold, color: _slate)),
        pw.SizedBox(height: 6),
        pw.TableHelper.fromTextArray(
          headers: ['Category', 'Amount (SAR)', '% of total'],
          headerDecoration: const pw.BoxDecoration(color: _emerald),
          headerStyle: pw.TextStyle(color: PdfColors.white, fontWeight: pw.FontWeight.bold),
          cellAlignments: {1: pw.Alignment.centerRight, 2: pw.Alignment.centerRight},
          data: byCat.entries
              .map((e) => [
                    e.key[0].toUpperCase() + e.key.substring(1),
                    e.value.toStringAsFixed(0),
                    total == 0 ? '-' : '${(e.value / total * 100).toStringAsFixed(1)}%',
                  ])
              .toList(),
        ),
        pw.SizedBox(height: 16),
        pw.Text('All expenses',
            style: pw.TextStyle(fontSize: 14, fontWeight: pw.FontWeight.bold, color: _slate)),
        pw.SizedBox(height: 6),
        pw.TableHelper.fromTextArray(
          headers: ['Date', 'Category', 'SAR', 'Note'],
          headerDecoration: const pw.BoxDecoration(color: _emerald),
          headerStyle: pw.TextStyle(color: PdfColors.white, fontWeight: pw.FontWeight.bold),
          cellStyle: const pw.TextStyle(fontSize: 9),
          cellAlignments: {2: pw.Alignment.centerRight},
          data: app.expenses
              .map((e) => [
                    DateFormat('d MMM yyyy').format(e.date),
                    e.category,
                    e.amountSar.toStringAsFixed(0),
                    e.note ?? '',
                  ])
              .toList(),
        ),
      ],
    ));
    await _share(doc, 'UmrahTrip-Expenses.pdf');
  }

  /// "Safar-e-Umrah" memories report: visited places with dates and notes.
  static Future<void> shareMemoriesReport(AppState app) async {
    final visited = app.planner.visits
        .where((v) => v.status == VisitStatus.visited)
        .toList()
      ..sort((a, b) =>
          (a.visitedAt ?? DateTime(0)).compareTo(b.visitedAt ?? DateTime(0)));

    final doc = pw.Document();
    doc.addPage(pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      footer: (_) => _footer(),
      build: (_) => [
        _header('My Travel Memories'),
        pw.SizedBox(height: 14),
        pw.Text(
            'Alhamdulillah — ${visited.length} ziyarat completed. May Allah accept this journey.',
            style: const pw.TextStyle(fontSize: 11, color: PdfColors.grey700)),
        pw.SizedBox(height: 12),
        ...visited.map((v) {
          final d = app.repo.byId(v.destinationId);
          return pw.Container(
            margin: const pw.EdgeInsets.only(bottom: 10),
            padding: const pw.EdgeInsets.all(12),
            decoration: pw.BoxDecoration(
              border: pw.Border.all(color: _gold, width: .8),
              borderRadius: pw.BorderRadius.circular(8),
            ),
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Row(
                    mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                    children: [
                      pw.Text(d?.nameEn ?? v.destinationId,
                          style: pw.TextStyle(
                              fontSize: 12,
                              fontWeight: pw.FontWeight.bold,
                              color: _emerald)),
                      pw.Text(
                          v.visitedAt == null
                              ? ''
                              : DateFormat('EEE, d MMM yyyy · HH:mm')
                                  .format(v.visitedAt!),
                          style: const pw.TextStyle(
                              fontSize: 9, color: PdfColors.grey600)),
                    ]),
                if (d != null)
                  pw.Text(d.summaryEn,
                      maxLines: 2,
                      style: const pw.TextStyle(
                          fontSize: 8.5, color: PdfColors.grey700)),
                if (v.notes != null && v.notes!.isNotEmpty)
                  pw.Padding(
                    padding: const pw.EdgeInsets.only(top: 4),
                    child: pw.Text('My note: ${v.notes}',
                        style: pw.TextStyle(
                            fontSize: 9.5,
                            fontStyle: pw.FontStyle.italic,
                            color: _slate)),
                  ),
                if (v.checkinLat != null)
                  pw.Text(
                      'Check-in: ${v.checkinLat!.toStringAsFixed(5)}, ${v.checkinLng!.toStringAsFixed(5)}',
                      style: const pw.TextStyle(
                          fontSize: 8, color: PdfColors.grey600)),
              ],
            ),
          );
        }),
      ],
    ));
    await _share(doc, 'UmrahTrip-Memories.pdf');
  }

  static pw.Widget _stat(String label, String value) => pw.Expanded(
        child: pw.Container(
          padding: const pw.EdgeInsets.all(10),
          decoration: pw.BoxDecoration(
            color: const PdfColor.fromInt(0xFFF8F7F2),
            border: pw.Border.all(color: _gold),
            borderRadius: pw.BorderRadius.circular(8),
          ),
          child: pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Text(label,
                  style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey700)),
              pw.Text(value,
                  style: pw.TextStyle(
                      fontSize: 13, fontWeight: pw.FontWeight.bold, color: _emerald)),
            ],
          ),
        ),
      );
}
